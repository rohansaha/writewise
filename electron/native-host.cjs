// Registers `writewise native-host` with the Chromium browsers on this machine as a native-messaging
// host, so the browser extension can fetch the API key from this app (cli/native-host.ts). Writes a
// wrapper script (the app's own binary run as Node, so no separate Node install is needed) and the
// host manifest into userData, then copies the manifest into every installed browser's
// NativeMessagingHosts folder (the registry on Windows). Idempotent; run again after an update.
const { app } = require('electron')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { execFileSync } = require('node:child_process')

const HOST_NAME = 'app.writewise.desktop'
/** The Chrome Web Store ID of the WriteWise extension (extension/STORE_LISTING.md). */
const STORE_EXTENSION_ID = 'hmdpffagdonhmmgdcohmbkjcijiieicn'

function browserLocations() {
  const home = os.homedir()
  if (process.platform === 'darwin') {
    const base = path.join(home, 'Library', 'Application Support')
    return [
      ['Chrome', path.join(base, 'Google', 'Chrome')],
      ['Chrome Beta', path.join(base, 'Google', 'Chrome Beta')],
      ['Chrome Canary', path.join(base, 'Google', 'Chrome Canary')],
      ['Chromium', path.join(base, 'Chromium')],
      ['Brave', path.join(base, 'BraveSoftware', 'Brave-Browser')],
      ['Edge', path.join(base, 'Microsoft Edge')],
      ['Arc', path.join(base, 'Arc', 'User Data')],
      ['Vivaldi', path.join(base, 'Vivaldi')],
      ['Opera', path.join(base, 'com.operasoftware.Opera')],
    ]
  }
  if (process.platform === 'linux') {
    const base = process.env.XDG_CONFIG_HOME || path.join(home, '.config')
    return [
      ['Chrome', path.join(base, 'google-chrome')],
      ['Chromium', path.join(base, 'chromium')],
      ['Brave', path.join(base, 'BraveSoftware', 'Brave-Browser')],
      ['Edge', path.join(base, 'microsoft-edge')],
      ['Vivaldi', path.join(base, 'vivaldi')],
    ]
  }
  return []
}

const WINDOWS_KEYS = [
  ['Chrome', 'HKCU\\Software\\Google\\Chrome\\NativeMessagingHosts'],
  ['Edge', 'HKCU\\Software\\Microsoft\\Edge\\NativeMessagingHosts'],
  ['Chromium', 'HKCU\\Software\\Chromium\\NativeMessagingHosts'],
  ['Brave', 'HKCU\\Software\\BraveSoftware\\Brave-Browser\\NativeMessagingHosts'],
]

const hostDir = () => path.join(app.getPath('userData'), 'native-host')

/**
 * Writes the wrapper and manifest and registers them with every browser found.
 * `enginePath` is the on-disk bin/writewise.mjs; `extensionIds` adds unpacked dev builds of the extension.
 */
function register({ enginePath, extensionIds = [] }) {
  const dir = hostDir()
  fs.mkdirSync(dir, { recursive: true })
  const isWin = process.platform === 'win32'
  const wrapper = path.join(dir, isWin ? 'writewise-native-host.cmd' : 'writewise-native-host.sh')
  const exe = process.execPath
  const script = isWin
    ? `@echo off\r\nrem Generated by WriteWise ${app.getVersion()}: native-messaging host for the browser extension.\r\nset ELECTRON_RUN_AS_NODE=1\r\n"${exe}" "${enginePath}" native-host\r\n`
    : `#!/bin/sh\n# Generated by WriteWise ${app.getVersion()}: native-messaging host for the browser extension.\nELECTRON_RUN_AS_NODE=1 exec "${exe}" "${enginePath}" native-host\n`
  fs.writeFileSync(wrapper, script, { mode: 0o755 })
  if (!isWin) { try { fs.chmodSync(wrapper, 0o755) } catch { /* fine */ } }

  const ids = Array.from(new Set([STORE_EXTENSION_ID, ...extensionIds.filter((id) => typeof id === 'string' && /^[a-p]{32}$/.test(id))]))
  const manifest = {
    name: HOST_NAME,
    description: 'WriteWise desktop app: hands the Anthropic API key to the WriteWise browser extension.',
    path: wrapper,
    type: 'stdio',
    allowed_origins: ids.map((id) => `chrome-extension://${id}/`),
  }
  const body = JSON.stringify(manifest, null, 2) + '\n'
  const manifestPath = path.join(dir, `${HOST_NAME}.json`)
  fs.writeFileSync(manifestPath, body)

  const browsers = []
  if (isWin) {
    for (const [name, key] of WINDOWS_KEYS) {
      try {
        execFileSync('reg', ['add', `${key}\\${HOST_NAME}`, '/ve', '/t', 'REG_SZ', '/d', manifestPath, '/f'], { stdio: 'ignore', windowsHide: true })
        browsers.push(name)
      } catch (err) { console.warn(`native host: could not register with ${name}:`, err.message) }
    }
  } else {
    for (const [name, dataDir] of browserLocations()) {
      if (!fs.existsSync(dataDir)) continue
      try {
        const target = path.join(dataDir, 'NativeMessagingHosts')
        fs.mkdirSync(target, { recursive: true })
        fs.writeFileSync(path.join(target, `${HOST_NAME}.json`), body)
        browsers.push(name)
      } catch (err) { console.warn(`native host: could not register with ${name}:`, err.message) }
    }
  }
  return { browsers, manifestPath, wrapper, ids }
}

/** Removes the registration from every browser and the files from userData. */
function unregister() {
  const removed = []
  if (process.platform === 'win32') {
    for (const [name, key] of WINDOWS_KEYS) {
      try { execFileSync('reg', ['delete', `${key}\\${HOST_NAME}`, '/f'], { stdio: 'ignore', windowsHide: true }); removed.push(name) } catch { /* not registered */ }
    }
  } else {
    for (const [name, dataDir] of browserLocations()) {
      const p = path.join(dataDir, 'NativeMessagingHosts', `${HOST_NAME}.json`)
      if (fs.existsSync(p)) { try { fs.rmSync(p); removed.push(name) } catch { /* fine */ } }
    }
  }
  try { fs.rmSync(hostDir(), { recursive: true, force: true }) } catch { /* fine */ }
  return removed
}

module.exports = { register, unregister, HOST_NAME, STORE_EXTENSION_ID }
